  labs(title = "", x = expression(N^"*"), y = "c") +
  geom_hline(yintercept = true_c, color = "red") +
  my_theme

ggsave("sim_alpha.eps", plot = alpha_plot, width = 20, height = 20, units = "cm")
ggsave("sim_c.eps",     plot = c_plot,     width = 20, height = 20, units = "cm")


# ── Section 4: Error measures — RMSE and MAE vs lag ──────────────────────────
# Figure 2c in the paper.
# Computes RMSE and MAE for both alpha-hat and c-hat across all MC runs
# at each value of N*, using rmse() and median_absolute_error() from
# GraphSupOU-Functions-Final.R.

error_data <- data.frame(
  lag        = lag_vector,
  med_alpha  = apply(alpha_matrix, 2, median_absolute_error, a = true_alpha),
  rmse_alpha = apply(alpha_matrix, 2, rmse,                   a = true_alpha),
  med_c      = apply(c_matrix,     2, median_absolute_error, a = true_c),
  rmse_c     = apply(c_matrix,     2, rmse,                   a = true_c)
)

error_long <- pivot_longer(error_data,
                           cols      = c(med_alpha, rmse_alpha, med_c, rmse_c),
                           names_to  = "variable",
                           values_to = "error")

p_error <- ggplot(error_long, aes(x = factor(lag), y = error,
                                  color = variable, group = variable)) +
  geom_line(linewidth = 0.5, linetype = "dotted") +
  geom_point(size = 3) +
  scale_x_discrete(labels = ifelse(lag_vector %% 10 == 0, lag_vector, "")) +
  scale_color_manual(
    values = c("med_alpha"  = "darkblue", "rmse_alpha" = "blue",
               "med_c"      = "darkgreen","rmse_c"     = "green"),
    labels = c(expression(MAE(alpha)), expression(MAE(c)),
               expression(RMSE(alpha)), expression(RMSE(c)))
  ) +
  labs(title = "", x = expression(N^"*"), y = "Error measure", color = "") +
  my_theme

ggsave("sim-error.eps", plot = p_error, width = 20, height = 20, units = "cm")


# ── Section 5: Violin plots at optimal lag N* = 40 ───────────────────────────
# Figure 2d in the paper.
# Shows the full distribution of (alpha-hat, c-hat) at N*=40, identified
# as the recommended lag in Section 4. Dashed lines mark true values.

opt_lag <- 40
opt_col <- which(lag_vector == opt_lag)

alpha_at_opt <- alpha_matrix[, opt_col]
c_at_opt     <- c_matrix[,     opt_col]

vio_data <- data.frame(
