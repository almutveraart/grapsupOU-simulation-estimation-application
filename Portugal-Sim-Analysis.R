ggsave("p_vio.eps", plot = p_vio, width = 20, height = 20, units = "cm")


# ── Section 6: Median heatmaps of estimated mean and variance ─────────────────
# Figures 2e and 2f in the paper.
# For each MC run, estimates mu_L and sigma^2_L using the Step 2 formulas
# (equation (9), Proposition 3.2) at the optimal lag N*=40:
#   mu_hat  = (1 - alpha_i) * K_i %*% colMeans(X)
#   var_hat = (1 - alpha_i) * (K_i %*% cov(X) + cov(X) %*% t(K_i))
# Then takes the componentwise median across all 1000 runs.
# True values: mu_L = 0, sigma^2_L = 5*I_d.

my_mean_var_list <- vector("list", length = MonteCarloNumber)

for (i in 1:MonteCarloNumber) {
  
  c_i     <- c_matrix[i,     opt_col]
  alpha_i <- alpha_matrix[i, opt_col]
  K_i     <- create_K(c_i, A_norm)
  
  file_name <- paste0("simdata/POR_sim_data_", i, ".txt")
  X         <- as.matrix(read.table(file_name, header = FALSE, sep = "\t"))
  
  mu_hat  <- (1 - alpha_i) * K_i %*% as.numeric(colMeans(X))
  var_hat <- (1 - alpha_i) * (K_i %*% cov(X) + cov(X) %*% t(K_i))
  
  my_mean_var_list[[i]] <- list(mean = mu_hat, var = var_hat)
}

# Componentwise median over 1000 MC runs
median_var_matrix <- matrix(0, 24, 24)
median_mu_vec     <- numeric(24)

for (ii in 1:24) {
  for (jj in 1:24) {
    median_var_matrix[ii, jj] <- median(sapply(1:MonteCarloNumber,
                                               function(k) my_mean_var_list[[k]]$var[ii, jj]))
  }
  median_mu_vec[ii] <- median(sapply(1:MonteCarloNumber,
                                     function(k) my_mean_var_list[[k]]$mean[ii]))
}

# Figure 2f: median estimated variance heatmap
# Diagonal values are annotated directly on the plot
var_data           <- melt(median_var_matrix)
colnames(var_data) <- c("Row", "Column", "Value")
var_data$Row       <- factor(var_data$Row)
var_data$Column    <- factor(var_data$Column)

p_var <- ggplot(var_data, aes(x = Row, y = Column, fill = Value)) +
  geom_tile() +
  scale_fill_gradient2(low = "blue", mid = "white", high = "red",
                       midpoint = 0, name = "Cov") +
  scale_x_discrete(breaks = seq(4, 24, by = 4), labels = as.character(seq(4, 24, by = 4))) +
  scale_y_discrete(breaks = paste0("X", seq(4, 24, by = 4)), labels = seq(4, 24, by = 4)) +
  geom_text(data = var_data %>% filter(as.numeric(as.character(Row)) == as.numeric(as.character(Column))),
            aes(label = round(Value, 2)), size = 5, color = "black") +
  labs(x = "Component", y = "Component") +
  my_theme

ggsave("estvar_median_sim.eps", plot = p_var, width = 20, height = 20, units = "cm")

