# ============================================================
# Portugal-Sim-Analysis.R
#
# Analysis of Monte Carlo simulation results for the graph supOU
# process, reproducing the figures of Section 4 of:
#
#   Mehta, S. and Veraart, A. E. D. (2026).
#   "Statistical inference for Lévy-driven graph supOU processes:
#    From short- to long-memory in high-dimensional time series."
#   arXiv:2502.08838 [stat.ME] (preprint).
#   https://arxiv.org/abs/2502.08838
#
# Must be run after Portugal-Sim.R has generated all 1000
# simulated datasets in the simdata/ subdirectory.
#
# Required input files (must be in the working directory):
#   adj_mat.csv                  -- 24x24 adjacency matrix for
#                                   the Portuguese subnetwork
#   simdata/POR_sim_data_i.txt   -- simulated datasets (i=1,...,1000)
#                                   generated by Portugal-Sim.R
#   GraphSupOU-Functions-Final.R -- defines find_max_eigen,
#                                   autocovariance, objective_function,
#                                   create_K, f, rmse,
#                                   median_absolute_error
#
# Output files (EPS):
#   sim_alpha.eps          -- boxplots of alpha-hat vs N*   (Figure 2a)
#   sim_c.eps              -- boxplots of c-hat vs N*       (Figure 2b)
#   sim-error.eps          -- RMSE and MAE vs N*            (Figure 2c)
#   p_vio.eps              -- violin plots at N*=40         (Figure 2d)
#   estmean_median_sim.eps -- median estimated Levy mean    (Figure 2e)
#   estvar_median_sim.eps  -- median estimated Levy var     (Figure 2f)
#   sim_pairs_contour.eps  -- (c-hat, alpha-hat) scatter plots (Figure 3)
#   sim_pairs_lag{N*}.eps  -- individual panels of Figure 3
#   sim_1step_results.rds  -- saved alpha_matrix and c_matrix
#   sim_1step_workspace.RData -- full workspace snapshot
#
# Sections:
#    1. Parallelised estimation of (alpha, c) for each MC run and lag
#    2. Extract parameter matrices
#    3. Boxplots of alpha and c estimates across lags (Figures 2a, 2b)
#    4. Error measures: RMSE and MAE vs lag (Figure 2c)
#    5. Violin plots at optimal lag N*=40 (Figure 2d)
#    6. Median heatmaps of estimated mean and variance (Figures 2e, 2f)
#    7. Scatter/density plots of (c-hat, alpha-hat) at selected lags (Figure 3)
#
# Dependencies: ggplot2, tidyr, reshape2, dplyr, patchwork,
#               parallel, doParallel, foreach
# Minimum requirements: R >= 4.1.0
# ============================================================

source("GraphSupOU-Functions-Final.R")

library(ggplot2)
library(tidyr)
library(reshape2)
library(dplyr)
library(patchwork)
library(parallel)
library(doParallel)
library(foreach)

# ── Setup ─────────────────────────────────────────────────────────────────────

Port_adjacency <- apply(as.matrix(read.csv(file = "adj_mat.csv")), 2, as.numeric)
A_norm         <- col_normalise_adjacency_matrix(Port_adjacency)

# True parameter values used in Portugal-Sim.R
MonteCarloNumber <- 1000
Delta            <- 1
true_alpha       <- 1.5
true_c           <- -0.8

# Common theme for all plots
my_theme <- theme(
  axis.title       = element_text(size = 30),
  axis.text        = element_text(size = 30),
  plot.title       = element_text(size = 30),
  legend.text      = element_text(size = 25),
  legend.title     = element_text(size = 25)
)

# Label mapping: columns correspond to N* = 5, 10, 15, ..., 100
# custom_labels() shows only multiples of 10 on the x-axis to avoid clutter
lag_vector      <- seq(5, 100, by = 5)
my_col          <- length(lag_vector)   # 20
original_labels <- paste0("V", seq(1, my_col))
label_map       <- setNames(lag_vector, original_labels)

custom_labels <- function(labels) {
  mapped <- as.integer(label_map[labels])
  ifelse(mapped %% 10 == 0, mapped, "")
}


# ── Section 1: Estimate (alpha, c) for each MC run and each lag ───────────────
# For each of the 1000 simulated datasets and each N* in lag_vector,
# minimise the Gamma supOU loss function (14) via L-BFGS-B with box
# constraints: c in (-1, 1), alpha in (1, 10).
# Eigenvalues up to lag 100 are computed once per run and sliced inside
# the inner loop — avoids redundant recomputation.
# Results are collected as lists and unpacked in Section 2.

n_cores <- detectCores() - 1
cat(paste("Using", n_cores, "cores\n"))
cl <- makeCluster(n_cores)
registerDoParallel(cl)

clusterExport(cl, varlist = c(
  "lag_vector", "my_col", "Delta",
  "find_max_eigen", "autocovariance",
  "objective_function"
))
clusterEvalQ(cl, library(expm))

my_parameter_list <- foreach(
  i              = 1:MonteCarloNumber,
  .packages      = "expm",
  .errorhandling = "pass"   # failed runs return an error object rather than aborting
) %dopar% {
  
  file_name <- paste0("simdata/POR_sim_data_", i, ".txt")
  X         <- as.matrix(read.table(file_name, header = FALSE, sep = "\t"))
  
  alpha_vector <- numeric(my_col)
  c_vector     <- numeric(my_col)
  
  # Compute all eigenvalues up to lag 100 once per run
  ev_all                   <- find_max_eigen(X, 100)
  max_real_eigenvalues_all <- ev_all$max_real_eigenvalues
  
  for (j in 1:my_col) {
    
    max_lag              <- lag_vector[j]
    max_real_eigenvalues <- max_real_eigenvalues_all[1:max_lag]
    h_values             <- (1:max_lag) * Delta
    
    fit <- optim(
      par      = c(0.5, 2),
      fn       = objective_function,
      h        = h_values,
      Delta    = Delta,
      observed = max_real_eigenvalues,
      method   = "L-BFGS-B",
      lower    = c(-0.9999, 1),
      upper    = c(0.9999, 10)
    )
    
    c_vector[j]     <- fit$par[1]
    alpha_vector[j] <- fit$par[2]
  }
  
  list(
    alpha_vector = alpha_vector,
    c_vector     = c_vector
  )
}

stopCluster(cl)

# Report any failed runs
failed <- which(sapply(my_parameter_list, inherits, "error"))
if (length(failed) > 0) {
  cat(paste("Warning: runs failed:", paste(failed, collapse = ", "), "\n"))
}
cat(paste("Completed", MonteCarloNumber - length(failed), "/",
          MonteCarloNumber, "MC runs\n"))


# ── Section 2: Extract parameter matrices ─────────────────────────────────────
# alpha_matrix: MonteCarloNumber x my_col matrix of alpha-hat estimates
# c_matrix:     MonteCarloNumber x my_col matrix of c-hat estimates
# Rows = MC runs, columns = values of N* in lag_vector.

alpha_matrix <- matrix(0, nrow = MonteCarloNumber, ncol = my_col)
c_matrix     <- matrix(0, nrow = MonteCarloNumber, ncol = my_col)

for (i in 1:MonteCarloNumber) {
  alpha_matrix[i, ] <- my_parameter_list[[i]]$alpha_vector
  c_matrix[i, ]     <- my_parameter_list[[i]]$c_vector
}

# Save results for potential downstream use
saveRDS(list(alpha_matrix = alpha_matrix, c_matrix = c_matrix),
        "sim_1step_results.rds")


# ── Section 3: Boxplots of alpha and c estimates across lags ──────────────────
# Figures 2a and 2b in the paper.
# Outliers are suppressed (outlier.shape = NA) for readability, as noted
# in the Figure 2 caption. The solid red line marks the true parameter value.

alpha_df   <- as.data.frame(alpha_matrix)
c_df       <- as.data.frame(c_matrix)

alpha_long <- melt(alpha_df, variable.name = "Column", value.name = "Alpha")
c_long     <- melt(c_df,     variable.name = "Column", value.name = "C")

alpha_long$Column <- as.factor(alpha_long$Column)
c_long$Column     <- as.factor(c_long$Column)

alpha_plot <- ggplot(alpha_long, aes(x = Column, y = Alpha)) +
