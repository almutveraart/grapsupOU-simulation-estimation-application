# ── Section 7: Scatter/density plots of (c-hat, alpha-hat) at selected lags ───
# Figure 3 in the paper.
# For each N* in contour_lags, plots the joint distribution of (c-hat, alpha-hat)
# across all 1000 MC runs as a scatter plot with 2D density contours overlaid.
# The red cross marks the true value (c_0, alpha_0) = (-0.8, 1.5).
# Density contours are suppressed if the cloud is too degenerate (near-zero
# variance or fewer than 10 valid runs) to avoid kernel density failures.

contour_lags <- c(10, 30, 40, 50, 70, 100)
plot_list    <- vector("list", length(contour_lags))

for (k in seq_along(contour_lags)) {
  plot_list[[k]] <- local({
    lag_k <- contour_lags[k]
    col_k <- which(lag_vector == lag_k)
    
    c_vals     <- c_matrix[,     col_k]
    alpha_vals <- alpha_matrix[, col_k]
    keep       <- is.finite(c_vals) & is.finite(alpha_vals)
    c_vals     <- c_vals[keep]
    alpha_vals <- alpha_vals[keep]
    
    df <- data.frame(c_hat = c_vals, alpha_hat = alpha_vals)
    
    # Guard against degenerate clouds where kernel density estimation would fail
    can_density <- (sd(c_vals)     > 1e-6 &
                      sd(alpha_vals) > 1e-6 &
                      length(c_vals) >= 10)
    
    p <- ggplot() +
      geom_point(data = df, aes(x = c_hat, y = alpha_hat),
                 size = 0.8, color = "#5b9bd5") +
      geom_vline(xintercept = true_c,     color = "red", linetype = "dashed", linewidth = 0.4) +
      geom_hline(yintercept = true_alpha, color = "red", linetype = "dashed", linewidth = 0.4) +
      annotate("point", x = true_c, y = true_alpha,
               color = "red", size = 4, shape = 3, stroke = 2) +
      coord_cartesian(xlim = c(-1, 1), ylim = c(1, 10)) +
      labs(title = bquote(N^"*" == .(lag_k)), x = "c", y = expression(alpha)) +
      my_theme +
      theme(plot.title = element_text(size = 25, hjust = 0.5))
    
    if (can_density) {
      p <- p + geom_density_2d(data = df, aes(x = c_hat, y = alpha_hat),
                               color = "steelblue", linewidth = 0.7)
    }
    p
  })
}

